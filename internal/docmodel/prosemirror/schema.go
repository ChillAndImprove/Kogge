// Package prosemirror applies the changes of the rich-text editor to documents on the server exactly as the editor
// applies them: node and mark types from the editor's schema, positions counted in UTF-16 code units, and the steps
// of ProseMirror's transforms. Shared drafts keep one document that all editors change step by step;
// with this package the server holds that document itself instead of trusting a browser's copy.
//
// The algorithms are a port of ProseMirror's prosemirror-model and prosemirror-transform modules (MIT licence, see
// LICENSE-ProseMirror); their tests compare the results with ProseMirror's for generated editing sessions.
package prosemirror

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

//go:embed schema.json
var editorSchema []byte

// Editor is the schema of Kogge's rich-text editor (generated by web/src/components/editor/schema.test.ts).
var Editor = mustSchema(editorSchema)

func mustSchema(spec []byte) *Schema {
	s, err := NewSchema(spec)
	if err != nil {
		panic(err)
	}
	return s
}

// Schema is a set of node and mark types.
type Schema struct {
	Nodes []*NodeType
	Marks []*MarkType
	Top   *NodeType
	Text  *NodeType
	nodes map[string]*NodeType
	marks map[string]*MarkType
}

// Attr is an attribute of a node or mark type.
type Attr struct {
	Name       string
	Default    any
	HasDefault bool
}

// NodeType is a type of node: its content expression, groups and attributes.
type NodeType struct {
	Name          string
	Groups        []string
	Attrs         []Attr
	Inline        bool // inline nodes (and text)
	Leaf          bool // no content
	Atom          bool // a leaf or an atom by its spec
	Text          bool
	InlineContent bool
	content       *contentMatch
	markSet       []*MarkType // nil: all marks are allowed in the content
	allMarks      bool
}

// MarkType is a type of mark.
type MarkType struct {
	Name     string
	Rank     int
	Attrs    []Attr
	excluded []*MarkType
}

type schemaSpec struct {
	TopNode string `json:"topNode"`
	Nodes   []struct {
		Name    string                                `json:"name"`
		Content string                                `json:"content"`
		Group   string                                `json:"group"`
		Inline  bool                                  `json:"inline"`
		Atom    bool                                  `json:"atom"`
		Marks   *string                               `json:"marks"`
		Attrs   map[string]map[string]json.RawMessage `json:"attrs"`
	} `json:"nodes"`
	Marks []struct {
		Name     string                                `json:"name"`
		Excludes *string                               `json:"excludes"`
		Attrs    map[string]map[string]json.RawMessage `json:"attrs"`
	} `json:"marks"`
}

func attrsOf(spec map[string]map[string]json.RawMessage) ([]Attr, error) {
	names := make([]string, 0, len(spec))
	for name := range spec {
		names = append(names, name)
	}
	sort.Strings(names)
	out := make([]Attr, 0, len(names))
	for _, name := range names {
		a := Attr{Name: name}
		if raw, ok := spec[name]["default"]; ok {
			a.HasDefault = true
			if err := json.Unmarshal(raw, &a.Default); err != nil {
				return nil, fmt.Errorf("default of %s: %w", name, err)
			}
		}
		out = append(out, a)
	}
	return out, nil
}

// NewSchema builds a schema from its description (see schema.json).
func NewSchema(spec []byte) (*Schema, error) {
	var in schemaSpec
	if err := json.Unmarshal(spec, &in); err != nil {
		return nil, err
	}
	s := &Schema{nodes: map[string]*NodeType{}, marks: map[string]*MarkType{}}
	for i, m := range in.Marks {
		attrs, err := attrsOf(m.Attrs)
		if err != nil {
			return nil, fmt.Errorf("mark %s: %w", m.Name, err)
		}
		t := &MarkType{Name: m.Name, Rank: i, Attrs: attrs}
		s.Marks = append(s.Marks, t)
		s.marks[m.Name] = t
	}
	for i, m := range in.Marks {
		t := s.Marks[i]
		switch {
		case m.Excludes == nil:
			t.excluded = []*MarkType{t}
		case *m.Excludes == "":
		default:
			list, err := s.gatherMarks(*m.Excludes)
			if err != nil {
				return nil, err
			}
			t.excluded = list
		}
	}
	for _, n := range in.Nodes {
		attrs, err := attrsOf(n.Attrs)
		if err != nil {
			return nil, fmt.Errorf("node %s: %w", n.Name, err)
		}
		t := &NodeType{Name: n.Name, Groups: strings.Fields(n.Group), Attrs: attrs, Text: n.Name == "text"}
		t.Inline = n.Inline || t.Text
		s.Nodes = append(s.Nodes, t)
		s.nodes[n.Name] = t
	}
	for i, n := range in.Nodes {
		t := s.Nodes[i]
		m, err := parseContent(n.Content, s)
		if err != nil {
			return nil, fmt.Errorf("node %s: %w", n.Name, err)
		}
		t.content, t.InlineContent = m, m.inline
		t.Leaf = m.empty
		t.Atom = t.Leaf || n.Atom
		switch {
		case n.Marks != nil && *n.Marks == "_":
			t.allMarks = true
		case n.Marks != nil && *n.Marks != "":
			list, err := s.gatherMarks(*n.Marks)
			if err != nil {
				return nil, err
			}
			t.markSet = list
		case n.Marks != nil && *n.Marks == "", !t.InlineContent:
			t.markSet = []*MarkType{}
		default:
			t.allMarks = true
		}
	}
	s.Top, s.Text = s.nodes[in.TopNode], s.nodes["text"]
	if s.Top == nil || s.Text == nil {
		return nil, fmt.Errorf("the schema needs the top node %q and text", in.TopNode)
	}
	return s, nil
}

func (s *Schema) gatherMarks(names string) ([]*MarkType, error) {
	var out []*MarkType
	for _, name := range strings.Fields(names) {
		if name == "_" {
			return append([]*MarkType(nil), s.Marks...), nil
		}
		t, ok := s.marks[name]
		if !ok {
			return nil, fmt.Errorf("unknown mark type %s", name)
		}
		out = append(out, t)
	}
	return out, nil
}

// NodeType returns the node type of a name, or nil.
func (s *Schema) NodeType(name string) *NodeType { return s.nodes[name] }

// MarkType returns the mark type of a name, or nil.
func (s *Schema) MarkType(name string) *MarkType { return s.marks[name] }

// InGroup reports whether the type belongs to a group.
func (t *NodeType) InGroup(group string) bool {
	for _, g := range t.Groups {
		if g == group {
			return true
		}
	}
	return false
}

// IsBlock reports whether nodes of the type are blocks.
func (t *NodeType) IsBlock() bool { return !t.Inline }

// IsTextblock reports whether the type is a block with inline content.
func (t *NodeType) IsTextblock() bool { return !t.Inline && t.InlineContent }

// AllowsMarkType reports whether the content of nodes of this type may carry marks of a type.
func (t *NodeType) AllowsMarkType(m *MarkType) bool {
	if t.allMarks {
		return true
	}
	for _, x := range t.markSet {
		if x == m {
			return true
		}
	}
	return false
}

func (t *NodeType) allowsMarks(marks []*Mark) bool {
	if t.allMarks {
		return true
	}
	for _, m := range marks {
		if !t.AllowsMarkType(m.Type) {
			return false
		}
	}
	return true
}

// validContent reports whether a fragment is valid content for the type, with marks the type allows.
func (t *NodeType) validContent(content Fragment) bool {
	end := t.content.matchFragment(t.content.start(), content, 0, content.ChildCount())
	if end == 0 || !t.content.validEnd(end) {
		return false
	}
	for _, c := range content.nodes {
		if !t.allowsMarks(c.marks) {
			return false
		}
	}
	return true
}

func (t *NodeType) checkContent(content Fragment) {
	if !t.validContent(content) {
		fail("Invalid content for node %s", t.Name)
	}
}

// compatibleContent reports whether the content of nodes of the two types can be joined.
func (t *NodeType) compatibleContent(other *NodeType) bool {
	return t == other || t.content.compatible(other.content)
}

// computeAttrs fills in the defaults of missing attributes; values for unknown attributes are dropped.
func computeAttrs(attrs []Attr, given map[string]any) map[string]any {
	if len(attrs) == 0 {
		return emptyAttrs
	}
	out := make(map[string]any, len(attrs))
	for _, a := range attrs {
		v, ok := given[a.Name]
		if !ok {
			if !a.HasDefault {
				fail("No value supplied for attribute %s", a.Name)
			}
			v = cloneValue(a.Default)
		}
		out[a.Name] = v
	}
	return out
}

var emptyAttrs = map[string]any{}

// cloneValue copies a JSON value, so that defaults are never shared between nodes.
func cloneValue(v any) any {
	switch x := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, e := range x {
			out[k] = cloneValue(e)
		}
		return out
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = cloneValue(e)
		}
		return out
	default:
		return v
	}
}
