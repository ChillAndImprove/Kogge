-- Registration tokens let agents register (global, or for the repositories of one code project).
CREATE TABLE agent_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  bytea NOT NULL UNIQUE,
    hint        text NOT NULL,
    project_id  bigint REFERENCES code_projects (id) ON DELETE CASCADE,
    description text NOT NULL DEFAULT '',
    created_by  bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz,
    uses        integer NOT NULL DEFAULT 0
);

CREATE TABLE agents (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL,
    project_id   bigint REFERENCES code_projects (id) ON DELETE CASCADE,
    secret_hash  bytea NOT NULL UNIQUE,
    labels       text[] NOT NULL DEFAULT '{}',
    os           text NOT NULL DEFAULT '',
    arch         text NOT NULL DEFAULT '',
    version      text NOT NULL DEFAULT '',
    enabled      boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz,
    last_ip      text NOT NULL DEFAULT ''
);

CREATE TABLE runs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id   bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    project_id      bigint NOT NULL,
    number          integer NOT NULL,
    pipeline        text NOT NULL,
    pipeline_name   text NOT NULL,
    event           text NOT NULL CHECK (event IN ('push', 'pull-request', 'schedule', 'manual', 'api')),
    branch          text,
    tag             text,
    target_branch   text, -- pull requests
    commit_sha      text NOT NULL,
    commit_subject  text NOT NULL DEFAULT '',
    pull_request_id bigint REFERENCES pull_requests (id) ON DELETE SET NULL,
    pull_request_number integer,
    triggered_by    bigint REFERENCES users (id) ON DELETE SET NULL,
    variables       jsonb NOT NULL DEFAULT '{}',
    state           text NOT NULL CHECK (state IN ('queued', 'running', 'succeeded', 'failed', 'cancelled', 'error')),
    error           text NOT NULL DEFAULT '',
    created_at      timestamptz NOT NULL DEFAULT now(),
    started_at      timestamptz,
    finished_at     timestamptz,
    UNIQUE (repository_id, number)
);
CREATE INDEX runs_repository_idx ON runs (repository_id, created_at DESC);
CREATE INDEX runs_commit_idx ON runs (repository_id, commit_sha);
CREATE INDEX runs_active_idx ON runs (state) WHERE state IN ('queued', 'running');

CREATE TABLE run_jobs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           bigint NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    stage_index      integer NOT NULL,
    stage_name       text NOT NULL,
    name             text NOT NULL,
    spec             jsonb NOT NULL,
    labels           text[] NOT NULL DEFAULT '{}',
    state            text NOT NULL CHECK (state IN ('created', 'pending', 'waiting', 'running', 'succeeded', 'failed', 'cancelled', 'skipped')),
    waiting_for      text NOT NULL DEFAULT '',
    attempt          integer NOT NULL DEFAULT 1,
    agent_id         bigint REFERENCES agents (id) ON DELETE SET NULL,
    token_hash       bytea UNIQUE,
    lease_until      timestamptz,
    deadline_at      timestamptz, -- end of the running attempt's timeout
    cancel_requested boolean NOT NULL DEFAULT false,
    environment      text,
    exit_code        integer,
    failure          text NOT NULL DEFAULT '',
    log_size         bigint NOT NULL DEFAULT 0,
    log_expired      boolean NOT NULL DEFAULT false,
    triggered_by     bigint REFERENCES users (id) ON DELETE SET NULL, -- who started this attempt (manual start, retry)
    created_at       timestamptz NOT NULL DEFAULT now(),
    started_at       timestamptz,
    finished_at      timestamptz
);
CREATE INDEX run_jobs_run_idx ON run_jobs (run_id, stage_index, id);
CREATE INDEX run_jobs_pending_idx ON run_jobs (id) WHERE state = 'pending';
CREATE INDEX run_jobs_running_idx ON run_jobs (lease_until) WHERE state = 'running';

CREATE TABLE artifacts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     bigint NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    job_id     bigint NOT NULL REFERENCES run_jobs (id) ON DELETE CASCADE,
    name       text NOT NULL,
    sha256     text NOT NULL,
    size       bigint NOT NULL,
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (job_id, name)
);
CREATE INDEX artifacts_expiry_idx ON artifacts (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE build_caches (
    id            bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    key           text NOT NULL,
    sha256        text NOT NULL,
    size          bigint NOT NULL,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    used_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (repository_id, key)
);

CREATE TABLE test_reports (
    job_id      bigint PRIMARY KEY REFERENCES run_jobs (id) ON DELETE CASCADE,
    total       integer NOT NULL,
    failed      integer NOT NULL,
    errors      integer NOT NULL,
    skipped     integer NOT NULL,
    duration_ms bigint NOT NULL,
    failures    jsonb NOT NULL DEFAULT '[]',
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Variables and secrets of the instance, a code project, a repository or an environment; narrower scopes win.
CREATE TABLE build_variables (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope      text NOT NULL CHECK (scope IN ('instance', 'project', 'repository', 'environment')),
    scope_id   bigint NOT NULL DEFAULT 0,
    name       text NOT NULL,
    value      text NOT NULL DEFAULT '',
    sealed     text,
    secret     boolean NOT NULL DEFAULT false,
    protected  boolean NOT NULL DEFAULT false,
    updated_by bigint REFERENCES users (id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (scope, scope_id, name)
);

CREATE TABLE environments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id    bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    name             text NOT NULL,
    description      text NOT NULL DEFAULT '',
    refs             text[] NOT NULL DEFAULT '{}',
    deployer_users   bigint[] NOT NULL DEFAULT '{}',
    deployer_groups  bigint[] NOT NULL DEFAULT '{}',
    approvals        integer NOT NULL DEFAULT 0,
    approver_users   bigint[] NOT NULL DEFAULT '{}',
    approver_groups  bigint[] NOT NULL DEFAULT '{}',
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (repository_id, name)
);

CREATE TABLE deployments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id bigint NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    run_id         bigint NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    job_id         bigint NOT NULL REFERENCES run_jobs (id) ON DELETE CASCADE,
    commit_sha     text NOT NULL,
    ref            text NOT NULL DEFAULT '',
    state          text NOT NULL CHECK (state IN ('waiting', 'running', 'succeeded', 'failed', 'cancelled')),
    created_by     bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    finished_at    timestamptz
);
CREATE INDEX deployments_environment_idx ON deployments (environment_id, created_at DESC);
CREATE INDEX deployments_job_idx ON deployments (job_id);

CREATE TABLE deployment_approvals (
    deployment_id bigint NOT NULL REFERENCES deployments (id) ON DELETE CASCADE,
    user_id       bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    approved      boolean NOT NULL,
    comment       text NOT NULL DEFAULT '',
    at            timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (deployment_id, user_id)
);

-- Results of builds (and external systems) for commits.
CREATE TABLE commit_statuses (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    sha           text NOT NULL,
    context       text NOT NULL,
    state         text NOT NULL CHECK (state IN ('pending', 'running', 'success', 'failure', 'error', 'cancelled')),
    description   text NOT NULL DEFAULT '',
    url           text NOT NULL DEFAULT '',
    run_id        bigint REFERENCES runs (id) ON DELETE CASCADE,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (repository_id, sha, context)
);

-- Pipeline settings of a repository.
CREATE TABLE repository_build_settings (
    repository_id     bigint PRIMARY KEY REFERENCES repositories (id) ON DELETE CASCADE,
    auto_cancel       boolean NOT NULL DEFAULT false, -- a new run cancels older runs of the pipeline on the branch
    max_parallel_jobs integer NOT NULL DEFAULT 0      -- 0: no limit
);

-- Schedules of pipelines, refreshed when the branch they name is pushed.
CREATE TABLE build_schedules (
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    pipeline      text NOT NULL,
    branch        text NOT NULL,
    cron          text NOT NULL,
    last_run_at   timestamptz,
    PRIMARY KEY (repository_id, pipeline, branch, cron)
);

