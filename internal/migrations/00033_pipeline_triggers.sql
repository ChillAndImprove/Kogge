-- Pipeline triggers: tokens of a repository with which other systems start its pipelines (concept §10.2). A trigger
-- acts for the user who created it, while that user may write to the repository.

-- +goose Up

CREATE TABLE pipeline_triggers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    description   text NOT NULL,
    token_hash    bytea NOT NULL UNIQUE,
    token_hint    text NOT NULL,
    created_by    bigint NOT NULL REFERENCES users (id),
    created_at    timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz,
    last_used_at  timestamptz
);

CREATE INDEX pipeline_triggers_repository ON pipeline_triggers (repository_id);

-- The trigger that started a run, by its description (the trigger may be gone).
ALTER TABLE runs ADD COLUMN trigger_name text;

