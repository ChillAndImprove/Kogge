-- Boards, sprints and dashboards (concept §7.7, §7.8, §7.11).

-- +goose Up

CREATE TABLE boards (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    name       text NOT NULL,
    type       text NOT NULL CHECK (type IN ('scrum', 'kanban')),
    query      text NOT NULL,
    config     jsonb NOT NULL DEFAULT '{}',
    owner_id   bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version    integer NOT NULL DEFAULT 1
);
CREATE INDEX boards_project_idx ON boards (project_id);

CREATE TABLE sprints (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id     bigint REFERENCES boards (id) ON DELETE SET NULL,
    name         text NOT NULL,
    goal         text NOT NULL DEFAULT '',
    state        text NOT NULL DEFAULT 'future' CHECK (state IN ('future', 'active', 'closed')),
    start_at     timestamptz,
    end_at       timestamptz,
    completed_at timestamptz,
    position     integer NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sprints_board_idx ON sprints (board_id, state);

-- An issue belongs to at most one open (future or active) sprint and keeps the closed sprints it went through.
CREATE TABLE issue_sprints (
    issue_id  bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    sprint_id bigint NOT NULL REFERENCES sprints (id) ON DELETE CASCADE,
    PRIMARY KEY (issue_id, sprint_id)
);
CREATE INDEX issue_sprints_sprint_idx ON issue_sprints (sprint_id);

-- Scope of a sprint when it started: the commitment for the sprint report and the velocity chart.
CREATE TABLE sprint_baselines (
    sprint_id bigint NOT NULL REFERENCES sprints (id) ON DELETE CASCADE,
    issue_id  bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    estimate  double precision,
    done      boolean NOT NULL DEFAULT false,
    PRIMARY KEY (sprint_id, issue_id)
);

CREATE TABLE dashboards (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    bigint NOT NULL REFERENCES users (id),
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    columns     integer NOT NULL DEFAULT 2 CHECK (columns BETWEEN 1 AND 3),
    widgets     jsonb NOT NULL DEFAULT '[]',
    shares      jsonb NOT NULL DEFAULT '[]',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    version     integer NOT NULL DEFAULT 1
);
CREATE INDEX dashboards_owner_idx ON dashboards (owner_id);

CREATE TABLE dashboard_favourites (
    dashboard_id bigint NOT NULL REFERENCES dashboards (id) ON DELETE CASCADE,
    user_id      bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    position     integer NOT NULL DEFAULT 0,
    PRIMARY KEY (dashboard_id, user_id)
);

