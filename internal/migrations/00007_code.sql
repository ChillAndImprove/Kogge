-- Code: code projects, repositories, permissions, SSH and deploy keys, branch permissions, pushes, pull requests
-- and the references between issues and code (concept §9, §11.1).

-- +goose Up

CREATE TABLE code_projects (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         text NOT NULL,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    version     integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX code_projects_key_key ON code_projects (upper(key));
CREATE UNIQUE INDEX code_projects_name_key ON code_projects (lower(name));

CREATE TABLE repositories (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     bigint NOT NULL REFERENCES code_projects (id),
    slug           text NOT NULL,
    name           text NOT NULL,
    description    text NOT NULL DEFAULT '',
    default_branch text NOT NULL DEFAULT 'main',
    archived       boolean NOT NULL DEFAULT false,
    settings       jsonb NOT NULL DEFAULT '{}',
    size_bytes     bigint NOT NULL DEFAULT 0,
    next_pr_number integer NOT NULL DEFAULT 1,
    pushed_at      timestamptz,
    created_by     bigint REFERENCES users (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    version        integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX repositories_slug_key ON repositories (project_id, lower(slug));

-- Former addresses of renamed or moved repositories.
CREATE TABLE repository_redirects (
    project_key   text NOT NULL,
    slug          text NOT NULL,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX repository_redirects_key ON repository_redirects (upper(project_key), lower(slug));

-- Grants on a code project (for all its repositories) or a single repository; the highest grant wins.
CREATE TABLE code_permissions (
    project_id    bigint REFERENCES code_projects (id) ON DELETE CASCADE,
    repository_id bigint REFERENCES repositories (id) ON DELETE CASCADE,
    permission    text NOT NULL CHECK (permission IN ('repo.read', 'repo.write', 'repo.admin', 'codeproject.admin')),
    holder_type   text NOT NULL CHECK (holder_type IN ('user', 'group', 'logged-in', 'anyone')),
    holder_id     bigint NOT NULL DEFAULT 0,
    CHECK ((project_id IS NULL) <> (repository_id IS NULL))
);
CREATE UNIQUE INDEX code_permissions_project_key ON code_permissions (project_id, permission, holder_type, holder_id)
    WHERE project_id IS NOT NULL;
CREATE UNIQUE INDEX code_permissions_repository_key ON code_permissions (repository_id, permission, holder_type, holder_id)
    WHERE repository_id IS NOT NULL;
CREATE INDEX code_permissions_holder_idx ON code_permissions (holder_type, holder_id);

-- SSH keys of users and deploy keys of repositories (read-only or with write access); fingerprints (SHA256) are
-- unique, so a key identifies one user or one repository.
CREATE TABLE ssh_keys (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          text NOT NULL CHECK (kind IN ('user', 'deploy')),
    user_id       bigint REFERENCES users (id) ON DELETE CASCADE,
    repository_id bigint REFERENCES repositories (id) ON DELETE CASCADE,
    name          text NOT NULL,
    public_key    text NOT NULL,
    fingerprint   text NOT NULL UNIQUE,
    write         boolean NOT NULL DEFAULT false,
    created_by    bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_used_at  timestamptz,
    CHECK ((kind = 'user' AND user_id IS NOT NULL AND repository_id IS NULL) OR
           (kind = 'deploy' AND repository_id IS NOT NULL AND user_id IS NULL))
);
CREATE INDEX ssh_keys_user_idx ON ssh_keys (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX ssh_keys_repository_idx ON ssh_keys (repository_id) WHERE repository_id IS NOT NULL;

-- Branch and tag permissions of a repository or (inherited by its repositories) a code project.
CREATE TABLE branch_permissions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    bigint REFERENCES code_projects (id) ON DELETE CASCADE,
    repository_id bigint REFERENCES repositories (id) ON DELETE CASCADE,
    pattern       text NOT NULL,
    kind          text NOT NULL CHECK (kind IN ('restrict-push', 'no-delete', 'no-rewrite', 'pull-request-only')),
    exempt_users  bigint[] NOT NULL DEFAULT '{}',
    exempt_groups bigint[] NOT NULL DEFAULT '{}',
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK ((project_id IS NULL) <> (repository_id IS NULL))
);
CREATE INDEX branch_permissions_repository_idx ON branch_permissions (repository_id);
CREATE INDEX branch_permissions_project_idx ON branch_permissions (project_id);

CREATE TABLE pushes (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    user_id       bigint REFERENCES users (id),
    deploy_key_id bigint REFERENCES ssh_keys (id) ON DELETE SET NULL,
    updates       jsonb NOT NULL,
    pushed_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX pushes_repository_idx ON pushes (repository_id, pushed_at DESC);

CREATE TABLE pull_requests (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    number        integer NOT NULL,
    title         text NOT NULL,
    description   jsonb NOT NULL,
    description_text text NOT NULL DEFAULT '',
    author_id     bigint REFERENCES users (id),
    source_branch text NOT NULL,
    target_branch text NOT NULL,
    source_sha    text NOT NULL,
    target_sha    text NOT NULL,
    merge_base    text NOT NULL,
    state         text NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'merged', 'declined')),
    draft         boolean NOT NULL DEFAULT false,
    conflicted    boolean NOT NULL DEFAULT false,
    merge_sha     text,
    closed_by     bigint REFERENCES users (id),
    closed_at     timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    version       integer NOT NULL DEFAULT 1,
    UNIQUE (repository_id, number)
);
CREATE UNIQUE INDEX pull_requests_open_key ON pull_requests (repository_id, source_branch, target_branch) WHERE state = 'open';
CREATE INDEX pull_requests_author_idx ON pull_requests (author_id, state);
CREATE INDEX pull_requests_updated_idx ON pull_requests (repository_id, state, updated_at DESC);

CREATE TABLE pull_request_reviewers (
    pull_request_id bigint NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
    user_id         bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    state           text NOT NULL DEFAULT 'unapproved' CHECK (state IN ('unapproved', 'approved', 'needs-work')),
    reviewed_sha    text,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (pull_request_id, user_id)
);
CREATE INDEX pull_request_reviewers_user_idx ON pull_request_reviewers (user_id);

-- Comments on the pull request, a file or a line of the diff (side old/new); tasks are comments to resolve.
CREATE TABLE pull_request_comments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id bigint NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
    parent_id       bigint REFERENCES pull_request_comments (id) ON DELETE CASCADE,
    author_id       bigint REFERENCES users (id),
    body            jsonb NOT NULL,
    body_text       text NOT NULL DEFAULT '',
    path            text,
    line            integer,
    side            text CHECK (side IN ('old', 'new')),
    commit_sha      text,
    line_text       text,
    outdated        boolean NOT NULL DEFAULT false,
    task            boolean NOT NULL DEFAULT false,
    resolved_at     timestamptz,
    resolved_by     bigint REFERENCES users (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    edited          boolean NOT NULL DEFAULT false
);
CREATE INDEX pull_request_comments_pr_idx ON pull_request_comments (pull_request_id, created_at);

-- What happened to a pull request: opened, rescoped (commits added or removed), reviewed, merged, declined, ….
CREATE TABLE pull_request_activities (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id bigint NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
    actor_id        bigint REFERENCES users (id),
    kind            text NOT NULL,
    data            jsonb NOT NULL DEFAULT '{}',
    at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX pull_request_activities_pr_idx ON pull_request_activities (pull_request_id, at);

-- References between issues and code (concept §11.1), by issue key so that keys of other projects resolve later.
CREATE TABLE issue_commits (
    issue_key     text NOT NULL,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    sha           text NOT NULL,
    message       text NOT NULL,
    author_name   text NOT NULL DEFAULT '',
    author_email  text NOT NULL DEFAULT '',
    author_id     bigint REFERENCES users (id) ON DELETE SET NULL,
    committed_at  timestamptz NOT NULL,
    PRIMARY KEY (issue_key, repository_id, sha)
);
CREATE INDEX issue_commits_repository_idx ON issue_commits (repository_id, sha);

CREATE TABLE issue_branches (
    issue_key     text NOT NULL,
    repository_id bigint NOT NULL REFERENCES repositories (id) ON DELETE CASCADE,
    branch        text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (issue_key, repository_id, branch)
);
CREATE INDEX issue_branches_repository_idx ON issue_branches (repository_id, branch);

CREATE TABLE issue_pull_requests (
    issue_key       text NOT NULL,
    pull_request_id bigint NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
    PRIMARY KEY (issue_key, pull_request_id)
);
CREATE INDEX issue_pull_requests_pr_idx ON issue_pull_requests (pull_request_id);

-- Commit commands (#comment, #time, #transition) run once per commit and issue (concept §11.3).
CREATE TABLE commit_commands_done (
    sha       text NOT NULL,
    issue_key text NOT NULL,
    result    text NOT NULL DEFAULT '',
    done_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (sha, issue_key)
);

