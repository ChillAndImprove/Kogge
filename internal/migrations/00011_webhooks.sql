-- Webhooks of the instance, issue projects, spaces, code projects and repositories (concept §12.6).

-- +goose Up

CREATE TABLE webhooks (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope         text NOT NULL CHECK (scope IN ('instance', 'project', 'space', 'code-project', 'repository')),
    scope_id      bigint NOT NULL DEFAULT 0,
    name          text NOT NULL,
    url           text NOT NULL,
    secret_sealed text NOT NULL,
    events        text[] NOT NULL DEFAULT '{}', -- empty: all events of the scope
    active        boolean NOT NULL DEFAULT true,
    created_by    bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX webhooks_scope_idx ON webhooks (scope, scope_id) WHERE active;

CREATE TABLE webhook_deliveries (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    webhook_id       bigint NOT NULL REFERENCES webhooks (id) ON DELETE CASCADE,
    event_id         uuid NOT NULL,
    event            text NOT NULL,
    payload          jsonb NOT NULL,
    state            text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'succeeded', 'failed')),
    attempts         integer NOT NULL DEFAULT 0,
    response_status  integer,
    response_excerpt text NOT NULL DEFAULT '',
    error            text NOT NULL DEFAULT '',
    duration_ms      integer,
    created_at       timestamptz NOT NULL DEFAULT now(),
    delivered_at     timestamptz
);
CREATE INDEX webhook_deliveries_hook_idx ON webhook_deliveries (webhook_id, id DESC);
CREATE INDEX webhook_deliveries_created_idx ON webhook_deliveries (created_at);

