-- Global configuration (concept §7.2).
CREATE TABLE issue_types (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    icon        text NOT NULL DEFAULT 'task',
    color       text NOT NULL DEFAULT 'blue',
    level       integer NOT NULL DEFAULT 0 CHECK (level IN (-1, 0, 1)),
    position    integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX issue_types_name_key ON issue_types (lower(name));

CREATE TABLE statuses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    category    text NOT NULL CHECK (category IN ('todo', 'inprogress', 'done')),
    position    integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX statuses_name_key ON statuses (lower(name));

CREATE TABLE resolutions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    position    integer NOT NULL DEFAULT 0,
    is_default  boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX resolutions_name_key ON resolutions (lower(name));

CREATE TABLE priorities (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    icon        text NOT NULL DEFAULT 'medium',
    color       text NOT NULL DEFAULT 'gray',
    position    integer NOT NULL DEFAULT 0,
    is_default  boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX priorities_name_key ON priorities (lower(name));

CREATE TABLE issue_link_types (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     text NOT NULL,
    outward  text NOT NULL,
    inward   text NOT NULL
);
CREATE UNIQUE INDEX issue_link_types_name_key ON issue_link_types (lower(name));

CREATE TABLE workflows (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    definition  jsonb NOT NULL,
    version     integer NOT NULL DEFAULT 1,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX workflows_name_key ON workflows (lower(name));

CREATE TABLE custom_fields (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text NOT NULL,
    description    text NOT NULL DEFAULT '',
    type           text NOT NULL CHECK (type IN ('text', 'textarea', 'number', 'date', 'datetime', 'select',
                       'multiselect', 'checkboxes', 'radio', 'cascading', 'user', 'multiuser', 'group', 'labels',
                       'url', 'version', 'multiversion')),
    options        jsonb NOT NULL DEFAULT '[]',
    config         jsonb NOT NULL DEFAULT '{}',
    project_ids    bigint[] NOT NULL DEFAULT '{}',
    issue_type_ids bigint[] NOT NULL DEFAULT '{}',
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX custom_fields_name_key ON custom_fields (lower(name));

-- Global project roles; members are per project.
CREATE TABLE project_roles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX project_roles_name_key ON project_roles (lower(name));

CREATE TABLE permission_schemes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX permission_schemes_name_key ON permission_schemes (lower(name));

CREATE TABLE permission_scheme_grants (
    scheme_id   bigint NOT NULL REFERENCES permission_schemes (id) ON DELETE CASCADE,
    permission  text NOT NULL,
    holder_type text NOT NULL CHECK (holder_type IN ('role', 'group', 'user', 'reporter', 'assignee', 'project-lead',
                    'logged-in', 'anyone')),
    holder_id   bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (scheme_id, permission, holder_type, holder_id)
);

CREATE TABLE security_schemes (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL,
    description      text NOT NULL DEFAULT '',
    default_level_id bigint
);
CREATE UNIQUE INDEX security_schemes_name_key ON security_schemes (lower(name));

CREATE TABLE security_levels (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id   bigint NOT NULL REFERENCES security_schemes (id) ON DELETE CASCADE,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    position    integer NOT NULL DEFAULT 0
);
ALTER TABLE security_schemes ADD FOREIGN KEY (default_level_id) REFERENCES security_levels (id) ON DELETE SET NULL;

CREATE TABLE security_level_members (
    level_id    bigint NOT NULL REFERENCES security_levels (id) ON DELETE CASCADE,
    holder_type text NOT NULL CHECK (holder_type IN ('role', 'group', 'user', 'reporter', 'assignee', 'project-lead')),
    holder_id   bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (level_id, holder_type, holder_id)
);

CREATE TABLE notification_schemes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX notification_schemes_name_key ON notification_schemes (lower(name));

CREATE TABLE notification_scheme_entries (
    scheme_id      bigint NOT NULL REFERENCES notification_schemes (id) ON DELETE CASCADE,
    event          text NOT NULL,
    recipient_type text NOT NULL CHECK (recipient_type IN ('reporter', 'assignee', 'watchers', 'project-lead',
                       'component-lead', 'user', 'group', 'role', 'user-field')),
    recipient_id   bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (scheme_id, event, recipient_type, recipient_id)
);

-- Projects (concept §7.1).
CREATE TABLE issue_projects (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key                    text NOT NULL UNIQUE,
    name                   text NOT NULL,
    description            text NOT NULL DEFAULT '',
    type                   text NOT NULL DEFAULT 'software' CHECK (type IN ('software', 'business')),
    category               text NOT NULL DEFAULT '',
    lead_id                bigint REFERENCES users (id),
    default_assignee       text NOT NULL DEFAULT 'unassigned' CHECK (default_assignee IN ('unassigned', 'lead')),
    permission_scheme_id   bigint NOT NULL REFERENCES permission_schemes (id),
    notification_scheme_id bigint REFERENCES notification_schemes (id),
    security_scheme_id     bigint REFERENCES security_schemes (id),
    default_workflow_id    bigint NOT NULL REFERENCES workflows (id),
    next_number            bigint NOT NULL DEFAULT 1,
    avatar                 text NOT NULL DEFAULT '',
    archived               boolean NOT NULL DEFAULT false,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    version                integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX issue_projects_name_key ON issue_projects (lower(name));

-- Current and former project keys, so old issue keys keep resolving.
CREATE TABLE issue_project_keys (
    key        text PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE
);

CREATE TABLE project_issue_types (
    project_id    bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    issue_type_id bigint NOT NULL REFERENCES issue_types (id),
    workflow_id   bigint REFERENCES workflows (id),
    position      integer NOT NULL DEFAULT 0,
    PRIMARY KEY (project_id, issue_type_id)
);

-- Field layout per project and issue type (issue_type_id 0 = the project's default layout).
CREATE TABLE project_field_layouts (
    project_id    bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    issue_type_id bigint NOT NULL DEFAULT 0,
    layout        jsonb NOT NULL,
    PRIMARY KEY (project_id, issue_type_id)
);

CREATE TABLE project_role_members (
    project_id     bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    role_id        bigint NOT NULL REFERENCES project_roles (id) ON DELETE CASCADE,
    principal_type text NOT NULL CHECK (principal_type IN ('user', 'group')),
    principal_id   bigint NOT NULL,
    PRIMARY KEY (project_id, role_id, principal_type, principal_id)
);
CREATE INDEX project_role_members_principal_idx ON project_role_members (principal_type, principal_id);

CREATE TABLE components (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    name             text NOT NULL,
    description      text NOT NULL DEFAULT '',
    lead_id          bigint REFERENCES users (id),
    default_assignee text NOT NULL DEFAULT 'none' CHECK (default_assignee IN ('none', 'component-lead', 'project-lead')),
    archived         boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX components_name_key ON components (project_id, lower(name));

CREATE TABLE versions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    name         text NOT NULL,
    description  text NOT NULL DEFAULT '',
    start_date   date,
    release_date date,
    released     boolean NOT NULL DEFAULT false,
    released_at  timestamptz,
    archived     boolean NOT NULL DEFAULT false,
    position     integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX versions_name_key ON versions (project_id, lower(name));

-- Issues (concept §7.5).
CREATE TABLE issues (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         bigint NOT NULL REFERENCES issue_projects (id),
    number             bigint NOT NULL,
    key                text NOT NULL UNIQUE,
    type_id            bigint NOT NULL REFERENCES issue_types (id),
    status_id          bigint NOT NULL REFERENCES statuses (id),
    priority_id        bigint REFERENCES priorities (id),
    resolution_id      bigint REFERENCES resolutions (id),
    summary            text NOT NULL,
    description        jsonb,
    description_text   text NOT NULL DEFAULT '',
    environment        text NOT NULL DEFAULT '',
    reporter_id        bigint REFERENCES users (id),
    creator_id         bigint NOT NULL REFERENCES users (id),
    assignee_id        bigint REFERENCES users (id),
    parent_id          bigint REFERENCES issues (id),
    security_level_id  bigint REFERENCES security_levels (id),
    due_date           date,
    original_estimate  bigint,
    remaining_estimate bigint,
    time_spent         bigint NOT NULL DEFAULT 0,
    labels             text[] NOT NULL DEFAULT '{}',
    fields             jsonb NOT NULL DEFAULT '{}',
    rank               text COLLATE "C" NOT NULL,
    votes              integer NOT NULL DEFAULT 0,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    resolved_at        timestamptz,
    status_changed_at  timestamptz NOT NULL DEFAULT now(),
    version            integer NOT NULL DEFAULT 1,
    search_tsv         tsvector,
    UNIQUE (project_id, number)
);
CREATE INDEX issues_project_status_idx ON issues (project_id, status_id);
CREATE INDEX issues_assignee_idx ON issues (assignee_id);
CREATE INDEX issues_reporter_idx ON issues (reporter_id);
CREATE INDEX issues_parent_idx ON issues (parent_id);
CREATE INDEX issues_rank_idx ON issues (rank);
CREATE INDEX issues_updated_idx ON issues (updated_at DESC);
CREATE INDEX issues_created_idx ON issues (created_at DESC);
CREATE INDEX issues_labels_idx ON issues USING gin (labels);
CREATE INDEX issues_fields_idx ON issues USING gin (fields jsonb_path_ops);
CREATE INDEX issues_search_idx ON issues USING gin (search_tsv);
CREATE INDEX issues_summary_trgm_idx ON issues USING gin (lower(summary) gin_trgm_ops);
CREATE INDEX issues_security_idx ON issues (security_level_id) WHERE security_level_id IS NOT NULL;

-- Former keys of moved issues.
CREATE TABLE issue_keys (
    key      text PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE
);

CREATE TABLE issue_components (
    issue_id     bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    component_id bigint NOT NULL REFERENCES components (id) ON DELETE CASCADE,
    PRIMARY KEY (issue_id, component_id)
);
CREATE INDEX issue_components_component_idx ON issue_components (component_id);

CREATE TABLE issue_versions (
    issue_id   bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    version_id bigint NOT NULL REFERENCES versions (id) ON DELETE CASCADE,
    kind       text NOT NULL CHECK (kind IN ('fix', 'affects')),
    PRIMARY KEY (issue_id, version_id, kind)
);
CREATE INDEX issue_versions_version_idx ON issue_versions (version_id, kind);

-- The change history: one row per change with its items (field, old/new value and display strings).
CREATE TABLE issue_changes (
    id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    actor_id bigint REFERENCES users (id),
    at       timestamptz NOT NULL DEFAULT now(),
    items    jsonb NOT NULL
);
CREATE INDEX issue_changes_issue_idx ON issue_changes (issue_id, at);
CREATE INDEX issue_changes_at_idx ON issue_changes (at);

CREATE TABLE issue_comments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id         bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    author_id        bigint REFERENCES users (id),
    body             jsonb NOT NULL,
    body_text        text NOT NULL DEFAULT '',
    visibility_type  text CHECK (visibility_type IN ('role', 'group')),
    visibility_id    bigint,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       bigint REFERENCES users (id),
    version          integer NOT NULL DEFAULT 1
);
CREATE INDEX issue_comments_issue_idx ON issue_comments (issue_id, created_at);

CREATE TABLE issue_attachments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id     bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    filename     text NOT NULL,
    content_type text NOT NULL,
    size         bigint NOT NULL,
    sha256       text NOT NULL REFERENCES blobs (sha256),
    author_id    bigint REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX issue_attachments_issue_idx ON issue_attachments (issue_id);

CREATE TABLE worklogs (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    author_id  bigint REFERENCES users (id),
    started_at timestamptz NOT NULL,
    seconds    bigint NOT NULL CHECK (seconds > 0),
    comment    text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX worklogs_issue_idx ON worklogs (issue_id, started_at);
CREATE INDEX worklogs_author_idx ON worklogs (author_id, started_at);

CREATE TABLE issue_links (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_type_id bigint NOT NULL REFERENCES issue_link_types (id) ON DELETE CASCADE,
    source_id    bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    target_id    bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    created_by   bigint REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (link_type_id, source_id, target_id),
    CHECK (source_id <> target_id)
);
CREATE INDEX issue_links_target_idx ON issue_links (target_id);

CREATE TABLE issue_votes (
    issue_id bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    user_id  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (issue_id, user_id)
);

-- Saved filters with sharing (concept §7.6).
CREATE TABLE saved_filters (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    bigint NOT NULL REFERENCES users (id),
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    query       text NOT NULL,
    columns     text[] NOT NULL DEFAULT '{}',
    shares      jsonb NOT NULL DEFAULT '[]',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX saved_filters_owner_name_key ON saved_filters (owner_id, lower(name));

CREATE TABLE saved_filter_favourites (
    filter_id bigint NOT NULL REFERENCES saved_filters (id) ON DELETE CASCADE,
    user_id   bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (filter_id, user_id)
);

