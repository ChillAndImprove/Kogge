CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        text NOT NULL,
    display_name    text NOT NULL,
    email           text,
    email_verified  boolean NOT NULL DEFAULT false,
    kind            text NOT NULL DEFAULT 'person' CHECK (kind IN ('person', 'service', 'system', 'placeholder')),
    status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled', 'anonymised')),
    oidc_issuer     text,
    oidc_subject    text,
    password_hash   text,
    failed_logins   integer NOT NULL DEFAULT 0,
    locked_until    timestamptz,
    locale          text,
    time_zone       text,
    theme           text,
    avatar_sha256   text,
    preferences     jsonb NOT NULL DEFAULT '{}',
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    last_login_at   timestamptz,
    UNIQUE (oidc_issuer, oidc_subject)
);
CREATE UNIQUE INDEX users_username_key ON users (lower(username)) WHERE status <> 'anonymised';
CREATE INDEX users_email_idx ON users (lower(email));
CREATE INDEX users_name_trgm_idx ON users USING gin ((lower(username || ' ' || display_name)) gin_trgm_ops);

CREATE TABLE groups (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    source      text NOT NULL DEFAULT 'local' CHECK (source IN ('local', 'oidc')),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX groups_name_key ON groups (lower(name));

CREATE TABLE group_members (
    group_id bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    user_id  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, user_id)
);
CREATE INDEX group_members_user_idx ON group_members (user_id);

CREATE TABLE sessions (
    id_hash         bytea PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    csrf_token      text NOT NULL,
    auth_method     text NOT NULL,
    oidc_sid        text,
    ip              inet,
    user_agent      text NOT NULL DEFAULT '',
    created_at      timestamptz NOT NULL DEFAULT now(),
    last_seen_at    timestamptz NOT NULL DEFAULT now(),
    idle_expires_at timestamptz NOT NULL,
    expires_at      timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_oidc_sid_idx ON sessions (oidc_sid) WHERE oidc_sid IS NOT NULL;
CREATE INDEX sessions_expiry_idx ON sessions (expires_at);

-- Pending OpenID Connect logins (state, nonce, PKCE verifier), valid for minutes.
CREATE TABLE oidc_logins (
    state        text PRIMARY KEY,
    nonce        text NOT NULL,
    verifier     text NOT NULL,
    return_to    text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE access_tokens (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name         text NOT NULL,
    token_hash   bytea NOT NULL UNIQUE,
    hint         text NOT NULL,
    scopes       text[] NOT NULL,
    expires_at   timestamptz,
    last_used_at timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX access_tokens_user_idx ON access_tokens (user_id);

-- Global permissions. principal_id is 0 for the special principals 'logged-in' and 'anyone'.
CREATE TABLE global_grants (
    permission     text NOT NULL,
    principal_type text NOT NULL CHECK (principal_type IN ('user', 'group', 'logged-in', 'anyone')),
    principal_id   bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (permission, principal_type, principal_id)
);

