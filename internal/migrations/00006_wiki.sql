-- The wiki: spaces, pages and blog posts with versions, drafts, restrictions, comments, attachments, labels and
-- templates (concept §8).

-- +goose Up

CREATE TABLE spaces (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key          text NOT NULL,
    name         text NOT NULL,
    description  text NOT NULL DEFAULT '',
    type         text NOT NULL DEFAULT 'team' CHECK (type IN ('team', 'personal')),
    owner_id     bigint REFERENCES users (id),
    categories   text[] NOT NULL DEFAULT '{}',
    home_page_id bigint,
    archived     boolean NOT NULL DEFAULT false,
    created_by   bigint REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    version      integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX spaces_key_key ON spaces (upper(key));
CREATE UNIQUE INDEX spaces_personal_key ON spaces (owner_id) WHERE type = 'personal';

-- Grants of space permissions (reference/permissions.md) to users, groups, logged-in users and anyone.
CREATE TABLE space_permissions (
    space_id    bigint NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
    permission  text NOT NULL,
    holder_type text NOT NULL CHECK (holder_type IN ('user', 'group', 'logged-in', 'anyone')),
    holder_id   bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (space_id, permission, holder_type, holder_id)
);
CREATE INDEX space_permissions_holder_idx ON space_permissions (holder_type, holder_id);

CREATE TABLE pages (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id        bigint NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
    parent_id       bigint REFERENCES pages (id) ON DELETE SET NULL,
    kind            text NOT NULL DEFAULT 'page' CHECK (kind IN ('page', 'blog')),
    status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'current', 'trashed', 'archived')),
    title           text NOT NULL,
    body            jsonb NOT NULL,
    body_text       text NOT NULL DEFAULT '',
    rank            text COLLATE "C" NOT NULL DEFAULT '',
    version         integer NOT NULL DEFAULT 0,
    creator_id      bigint REFERENCES users (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      bigint REFERENCES users (id),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    published_at    timestamptz,
    trashed_at      timestamptz,
    trashed_by      bigint REFERENCES users (id),
    -- Pages (this one and ancestors) whose view restrictions a reader must pass; empty = unrestricted.
    view_restricted_by bigint[] NOT NULL DEFAULT '{}',
    search_tsv      tsvector
);
CREATE INDEX pages_tree_idx ON pages (space_id, parent_id, rank);
CREATE UNIQUE INDEX pages_title_key ON pages (space_id, lower(title)) WHERE kind = 'page' AND status IN ('current', 'archived');
CREATE INDEX pages_search_idx ON pages USING gin (search_tsv);
CREATE INDEX pages_updated_idx ON pages (updated_at DESC);
CREATE INDEX pages_blog_idx ON pages (space_id, published_at DESC) WHERE kind = 'blog';

ALTER TABLE spaces ADD CONSTRAINT spaces_home_page_fk FOREIGN KEY (home_page_id) REFERENCES pages (id) ON DELETE SET NULL;

CREATE TABLE page_versions (
    page_id    bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    version    integer NOT NULL,
    title      text NOT NULL,
    body       jsonb NOT NULL,
    author_id  bigint REFERENCES users (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    message    text NOT NULL DEFAULT '',
    minor      boolean NOT NULL DEFAULT false,
    PRIMARY KEY (page_id, version)
);

-- Personal drafts (autosaved while editing).
CREATE TABLE page_drafts (
    page_id      bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    user_id      bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title        text NOT NULL,
    body         jsonb NOT NULL,
    base_version integer NOT NULL,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (page_id, user_id)
);

CREATE TABLE page_restrictions (
    page_id     bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    kind        text NOT NULL CHECK (kind IN ('view', 'edit')),
    holder_type text NOT NULL CHECK (holder_type IN ('user', 'group')),
    holder_id   bigint NOT NULL,
    PRIMARY KEY (page_id, kind, holder_type, holder_id)
);

CREATE TABLE page_labels (
    page_id bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    label   text NOT NULL,
    PRIMARY KEY (page_id, label)
);
CREATE INDEX page_labels_label_idx ON page_labels (label);

CREATE TABLE page_comments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id     bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    parent_id   bigint REFERENCES page_comments (id) ON DELETE CASCADE,
    author_id   bigint REFERENCES users (id),
    body        jsonb NOT NULL,
    body_text   text NOT NULL DEFAULT '',
    anchor      text,
    anchor_text text,
    resolved_at timestamptz,
    resolved_by bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    edited      boolean NOT NULL DEFAULT false
);
CREATE INDEX page_comments_page_idx ON page_comments (page_id, created_at);

CREATE TABLE page_likes (
    page_id    bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (page_id, user_id)
);

CREATE TABLE comment_likes (
    comment_id bigint NOT NULL REFERENCES page_comments (id) ON DELETE CASCADE,
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (comment_id, user_id)
);

-- Attachments keep their versions: rows with the same file name and increasing version numbers.
CREATE TABLE page_attachments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id      bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    filename     text NOT NULL,
    version      integer NOT NULL DEFAULT 1,
    content_type text NOT NULL,
    size         bigint NOT NULL,
    sha256       text NOT NULL,
    comment      text NOT NULL DEFAULT '',
    author_id    bigint REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (page_id, filename, version)
);

CREATE TABLE page_templates (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    bigint REFERENCES spaces (id) ON DELETE CASCADE,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    kind        text NOT NULL DEFAULT 'page' CHECK (kind IN ('page', 'blog')),
    body        jsonb NOT NULL,
    labels      text[] NOT NULL DEFAULT '{}',
    builtin     text,
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX page_templates_space_idx ON page_templates (space_id);

CREATE TABLE space_favourites (
    space_id bigint NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
    user_id  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (space_id, user_id)
);

-- Recently viewed pages per user.
CREATE TABLE page_visits (
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    page_id    bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    visited_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, page_id)
);
CREATE INDEX page_visits_recent_idx ON page_visits (user_id, visited_at DESC);

-- Who has a page open or is editing it (heartbeats).
CREATE TABLE page_presence (
    page_id bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    editing boolean NOT NULL DEFAULT false,
    seen_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (page_id, user_id)
);

-- Issue keys mentioned by current pages (concept §11.1), for "mentioned in" on issues.
CREATE TABLE page_issue_refs (
    page_id   bigint NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
    issue_key text NOT NULL,
    PRIMARY KEY (page_id, issue_key)
);
CREATE INDEX page_issue_refs_key_idx ON page_issue_refs (issue_key);

