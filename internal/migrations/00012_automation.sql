-- Automation rules of issue projects (concept §11.4): events of code and builds change the issues they name.

-- +goose Up

CREATE TABLE automation_rules (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES issue_projects (id) ON DELETE CASCADE,
    name        text NOT NULL,
    trigger     text NOT NULL CHECK (trigger IN ('branch.created', 'commit.pushed', 'pull-request.opened', 'pull-request.merged',
                    'pull-request.declined', 'build.failed', 'deployment.succeeded')),
    environment text NOT NULL DEFAULT '', -- deployment.succeeded: only this environment ('' any)
    issue_types bigint[] NOT NULL DEFAULT '{}', -- condition: the issue has one of these types ('{}' any)
    statuses    bigint[] NOT NULL DEFAULT '{}', -- condition: the issue is in one of these statuses ('{}' any)
    action      text NOT NULL CHECK (action IN ('transition', 'comment', 'assign', 'fix-version')),
    params      jsonb NOT NULL DEFAULT '{}',
    active      boolean NOT NULL DEFAULT true,
    created_by  bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX automation_rules_project_idx ON automation_rules (project_id, trigger) WHERE active;

-- What the rules did, once per rule, issue and occurrence of the trigger.
CREATE TABLE automation_runs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     bigint NOT NULL REFERENCES automation_rules (id) ON DELETE CASCADE,
    issue_key   text NOT NULL,
    occurrence  text NOT NULL, -- e.g. pull-request:42, commit:<sha>, run:7, deployment:3
    result      text NOT NULL CHECK (result IN ('done', 'skipped', 'failed')),
    message     text NOT NULL DEFAULT '',
    at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (rule_id, issue_key, occurrence)
);
CREATE INDEX automation_runs_rule_idx ON automation_runs (rule_id, at DESC);

