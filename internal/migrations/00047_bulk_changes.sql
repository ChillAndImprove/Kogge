-- Bulk changes of issues (concept §7.5): edit, transition, move, delete and watch many issues at once, run as a
-- background job with a result per issue.

-- +goose Up

-- The project permission issue.bulk-change: whoever may edit issues may change them in bulk. Every bulk change
-- still checks the permission its action needs on each issue, so the grant adds no power over single issues.
INSERT INTO permission_scheme_grants (scheme_id, permission, holder_type, holder_id)
SELECT scheme_id, 'issue.bulk-change', holder_type, holder_id FROM permission_scheme_grants WHERE permission = 'issue.edit'
ON CONFLICT DO NOTHING;

-- The former keys of an issue (after it moved to another project, or its project's key changed).
CREATE INDEX issue_keys_issue_idx ON issue_keys (issue_id);

CREATE TABLE issue_bulk_changes (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     bigint NOT NULL REFERENCES users (id),
    action       text NOT NULL CHECK (action IN ('edit', 'transition', 'move', 'delete', 'watch', 'unwatch')),
    -- What to do: the values of the fields, the status, the target project and the mappings.
    params       jsonb NOT NULL,
    -- Send the summary notifications; only administrators of all the issues' projects may leave them out.
    notify       boolean NOT NULL DEFAULT true,
    summary_sent boolean NOT NULL DEFAULT false,
    -- The language of the results' messages, and whether the request could administer (token scopes).
    lang         text NOT NULL DEFAULT 'en',
    admin_scope  boolean NOT NULL DEFAULT true,
    state        text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'running', 'done', 'failed')),
    total        integer NOT NULL,
    processed    integer NOT NULL DEFAULT 0,
    error        text NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    started_at   timestamptz,
    finished_at  timestamptz
);
CREATE INDEX issue_bulk_changes_actor_idx ON issue_bulk_changes (actor_id, created_at DESC);

-- The issues of a bulk change in the order they were chosen, with what became of each. Deleted issues keep their
-- result, so there is no reference to the issue.
CREATE TABLE issue_bulk_items (
    change_id  bigint NOT NULL REFERENCES issue_bulk_changes (id) ON DELETE CASCADE,
    position   integer NOT NULL,
    issue_id   bigint,
    issue_key  text NOT NULL,
    new_key    text,
    result     text NOT NULL DEFAULT 'pending' CHECK (result IN ('pending', 'done', 'skipped', 'failed')),
    code       text NOT NULL DEFAULT '',
    message    text NOT NULL DEFAULT '',
    -- Who is to hear of the change of this issue (in the summary notification).
    recipients bigint[] NOT NULL DEFAULT '{}',
    PRIMARY KEY (change_id, position)
);
CREATE INDEX issue_bulk_items_issue_idx ON issue_bulk_items (issue_id);

